            let arg = row.0 * D + row.1 * M + row.2 * N + row.3 * F + row.4 * O
            psi += sin(arg) * (row.5 + row.6 * T)
            eps += cos(arg) * (row.7 + row.8 * T)
        }
        let sec = Double.pi / 180 / 3600
        return (psi * 0.0001 * sec, eps * 0.0001 * sec)
    }

