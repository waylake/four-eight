    static func nutation(jde: Double) -> (dPsi: Double, dEps: Double) {
        let T = (jde - 2451545.0) / 36525.0
        let deg = Double.pi / 180.0
        func horner(_ t: Double, _ c: [Double]) -> Double {
            c.reversed().reduce(0) { $0 * t + $1 }
        }
        let D = horner(T, [297.85036, 445267.11148, -0.0019142, 1.0 / 189474]) * deg
        let M = horner(T, [357.52772, 35999.050340, -0.0001603, -1.0 / 300000]) * deg
        let N = horner(T, [134.96298, 477198.867398, 0.0086972, 1.0 / 5620]) * deg
        let F = horner(T, [93.27191, 483202.017538, -0.0036825, 1.0 / 327270]) * deg
        let O = horner(T, [125.04452, -1934.136261, 0.0020708, 1.0 / 450000]) * deg

        var psi = 0.0, eps = 0.0
        // 작은 항부터 역순 누적.
